/** The classes the pool sorts its compounds into. */
export type CompoundClass =
  | 'metal-oxide'
  | 'nonmetal-oxide'
  | 'hydroxide'
  | 'peroxide'
  | 'acid'
  | 'covalent';

/** Whether a compound is met at school or at university. */
export type CompoundLevel = 'school' | 'university';

/** A compound of the pool, without its names. */
export interface Compound {
  /** The formula, as a question shows it. */
  formula: string;
  level: CompoundLevel;
  classes: readonly CompoundClass[];
}

